[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [Parameter(Mandatory = $true)]
    [string]$TargetRoot,

    [Parameter(Mandatory = $true)]
    [ValidateNotNullOrEmpty()]
    [string]$ProjectName,

    [string]$WorkflowRoot = '',

    [switch]$Force,

    [switch]$DryRun
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Get-FullPath([string]$Path) {
    return [System.IO.Path]::GetFullPath((Resolve-Path -LiteralPath $Path -ErrorAction Stop).Path)
}

function Get-RelativePath([string]$BasePath, [string]$Path) {
    $baseUri = [System.Uri]((Get-FullPath $BasePath).TrimEnd([System.IO.Path]::DirectorySeparatorChar) + [System.IO.Path]::DirectorySeparatorChar)
    $pathUri = [System.Uri](Get-FullPath $Path)
    return [System.Uri]::UnescapeDataString($baseUri.MakeRelativeUri($pathUri).ToString()).Replace('/', [System.IO.Path]::DirectorySeparatorChar)
}

function Assert-SafeTarget([string]$SourceRoot, [string]$DestinationRoot) {
    $source = (Get-FullPath $SourceRoot).TrimEnd([System.IO.Path]::DirectorySeparatorChar)
    $destination = [System.IO.Path]::GetFullPath($DestinationRoot).TrimEnd([System.IO.Path]::DirectorySeparatorChar)
    $comparison = [System.StringComparison]::OrdinalIgnoreCase
    if ($destination.Equals($source, $comparison) -or $destination.StartsWith($source + [System.IO.Path]::DirectorySeparatorChar, $comparison)) {
        throw "TargetRoot must not be the workflow source directory or a child of it: $destination"
    }
}

function Add-FilePlan([System.Collections.Generic.List[object]]$Plan, [string]$Source, [string]$Destination) {
    $safeSource = if ([string]::IsNullOrWhiteSpace($Source)) { $null } else { $Source }
    $Plan.Add([pscustomobject]@{ Source = $safeSource; Destination = $Destination })
}

if ([string]::IsNullOrWhiteSpace($WorkflowRoot)) {
    $WorkflowRoot = Split-Path -Parent $PSScriptRoot
}

if (-not (Test-Path -LiteralPath $WorkflowRoot -PathType Container)) {
    throw "WorkflowRoot does not exist: $WorkflowRoot"
}

$WorkflowRoot = Get-FullPath $WorkflowRoot
$TargetRoot = [System.IO.Path]::GetFullPath($TargetRoot)
Assert-SafeTarget -SourceRoot $WorkflowRoot -DestinationRoot $TargetRoot

$sourceManifest = Join-Path $WorkflowRoot 'MANIFEST.json'
if (-not (Test-Path -LiteralPath $sourceManifest -PathType Leaf)) {
    throw "MANIFEST.json was not found under WorkflowRoot: $sourceManifest"
}

$manifest = Get-Content -LiteralPath $sourceManifest -Raw | ConvertFrom-Json
$plan = [System.Collections.Generic.List[object]]::new()

$coreFiles = @(
    'README.md', 'WORKFLOW.md', 'SKILL.md', 'AGENTS.md', 'CHECKLIST.md',
    'project-state.json'
)
foreach ($relative in $coreFiles) {
    $source = Join-Path $WorkflowRoot $relative
    if (Test-Path -LiteralPath $source -PathType Leaf) {
        Add-FilePlan $plan $source (Join-Path (Join-Path $TargetRoot 'workflow') $relative)
    }
}

$directories = @('standards', 'templates', 'phases', 'security', 'harness', 'examples', 'decisions')
foreach ($directory in $directories) {
    $sourceDirectory = Join-Path $WorkflowRoot $directory
    if (-not (Test-Path -LiteralPath $sourceDirectory -PathType Container)) {
        continue
    }
    Get-ChildItem -LiteralPath $sourceDirectory -Recurse -File | ForEach-Object {
        $relative = Get-RelativePath -BasePath $WorkflowRoot -Path $_.FullName
        Add-FilePlan $plan $_.FullName (Join-Path (Join-Path $TargetRoot 'workflow') $relative)
    }
}

$knowledgeFiles = @(
    'knowledge/README.md',
    'knowledge/WEB_APP_PROBLEM_CATALOG.md',
    'knowledge/BACKEND_PROBLEM_PLAYBOOK.md',
    'knowledge/DOMAIN_ADAPTATION_GUIDE.md',
    'knowledge/WEB_APP_PROBLEM_CATALOG_RESEARCH_2026-08-22.md',
    'knowledge/COMMERCE_SYSTEMS_PLAYBOOK.md',
    'knowledge/RECOMMENDATION_SEARCH_RANKING_PLAYBOOK.md',
    'knowledge/DASHBOARD_ANALYTICS_PLAYBOOK.md',
    'knowledge/TRANSACTION_CONCURRENCY_PLAYBOOK.md',
    'knowledge/REPOSITORY_CI_PATTERNS_PLAYBOOK.md',
    'knowledge/COMMERCE_RECOMMENDATION_POLICY_RESEARCH_2026-08-22.md',
    'knowledge/THEME_I18N_RESEARCH_2026-08-22.md'
)
foreach ($relative in $knowledgeFiles) {
    $source = Join-Path $WorkflowRoot $relative
    if (Test-Path -LiteralPath $source -PathType Leaf) {
        Add-FilePlan $plan $source (Join-Path (Join-Path $TargetRoot 'workflow') $relative)
    }
}

$generatedFiles = @{
    'knowledge/PROJECT_CONTEXT.md' = @"
# Project Context — $ProjectName

> Generated by `init-workflow.ps1`. Replace this placeholder with the real project context before implementation.

- **Project name:** $ProjectName
- **Product/domain:** `<describe the product and domain>`
- **Users/roles:** `<list user segments and roles>`
- **Frontend stack:** `<replace with actual stack>`
- **Backend stack:** `<replace with actual stack>`
- **Database/storage:** `<replace with actual data stores>`
- **Runtime/deployment:** `<replace with actual environments>`
- **Canonical source locations:** `<list important paths>`
- **Known constraints:** `<list constraints>`
- **Owner:** `<person/team>`
- **Last verified:** `<YYYY-MM-DD>`

## First actions

1. Replace all placeholders in this file.
2. Create a Product Discovery Brief for the first feature.
3. Review `standards/README.md` and select the required standards by risk tier.
4. Run the available harness checks before changing application source.
"@
    'knowledge/DOMAIN_RULES.md' = @"
# Domain Rules — $ProjectName

Record confirmed business rules here. Do not infer rules from UI labels or error messages.

| Rule ID | Rule | Source/evidence | Owner | Status |
|---|---|---|---|---|
| DOM-001 | `<replace with a confirmed domain invariant>` | `<source>` | `<owner>` | `draft` |
"@
    'knowledge/KNOWN_FAILURES.md' = @"
# Known Failures — $ProjectName

Record reproducible failures, their evidence and prevention controls. Do not store secrets or raw production data.

| ID | Failure | Impact | Reproduction/evidence | Control | Owner | Status |
|---|---|---|---|---|---|---|
| FAIL-001 | `<replace with a known failure or remove this row>` | `<impact>` | `<evidence>` | `<control>` | `<owner>` | `open` |
"@
}
foreach ($entry in $generatedFiles.GetEnumerator()) {
    Add-FilePlan $plan $null (Join-Path (Join-Path $TargetRoot 'workflow') $entry.Key)
}

$targetManifest = Join-Path (Join-Path $TargetRoot 'workflow') 'MANIFEST.json'
Add-FilePlan $plan $sourceManifest $targetManifest

$conflicts = @($plan | Where-Object { Test-Path -LiteralPath $_.Destination -PathType Leaf })
if ($conflicts.Count -gt 0 -and -not $Force) {
    $conflictList = ($conflicts | Select-Object -ExpandProperty Destination) -join [Environment]::NewLine
    throw "Refusing to overwrite existing files. Use -Force only after reviewing this list:`n$conflictList"
}

if ($DryRun) {
    Write-Output "DRY_RUN: would create $($plan.Count) workflow files under $TargetRoot"
    $plan | ForEach-Object { Write-Output ("  " + $_.Destination) }
    return
}

foreach ($item in $plan) {
    $parent = Split-Path -Parent $item.Destination
    New-Item -ItemType Directory -Path $parent -Force | Out-Null
    if ($null -ne $item.Source) {
        Copy-Item -LiteralPath $item.Source -Destination $item.Destination -Force:$Force
    } else {
        $relative = $null
        foreach ($key in $generatedFiles.Keys) {
            if ($item.Destination -eq (Join-Path (Join-Path $TargetRoot 'workflow') $key)) {
                $relative = $key
                break
            }
        }
        if ($null -eq $relative) {
            throw "Generated file is not registered: $($item.Destination)"
        }
        Set-Content -LiteralPath $item.Destination -Value $generatedFiles[$relative] -Encoding UTF8 -NoNewline
    }
}

$workflowDestination = Join-Path $TargetRoot 'workflow'
$files = @(Get-ChildItem -LiteralPath $workflowDestination -Recurse -File | ForEach-Object { Get-RelativePath -BasePath $workflowDestination -Path $_.FullName })
$manifestObject = [ordered]@{
    name = 'web-app-factory-workflow'
    version = 'bootstrap-1.0.0'
    generated_at = (Get-Date).ToUniversalTime().ToString('o')
    generated_by = 'init-workflow.ps1'
    project_name = $ProjectName
    source_manifest_version = [string]$manifest.version
    entrypoints = @('MANIFEST.json', 'README.md', 'WORKFLOW.md', 'SKILL.md', 'standards/README.md')
    files = @($files | Sort-Object)
    security_policy = [ordered]@{
        contains_real_secrets = $false
        contains_production_credentials = $false
        requires_human_review_before_deploy = $true
    }
}
$manifestJson = $manifestObject | ConvertTo-Json -Depth 8
Set-Content -LiteralPath $targetManifest -Value $manifestJson -Encoding UTF8

Write-Output "BOOTSTRAP_COMPLETE"
Write-Output "ProjectRoot: $TargetRoot"
Write-Output "WorkflowRoot: $workflowDestination"
Write-Output "FilesCreated: $($files.Count)"
Write-Output "Next: replace workflow/knowledge placeholders and create the first change with new-change.ps1"
